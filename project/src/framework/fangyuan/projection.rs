//! Runtime projection and special-surface fallback contracts.
//!
//! Catalog projection values describe authoring intent.  The v0 renderer only
//! has stable mesh UVs, so this module is the single place that maps that
//! intent to a supported projection and records a diagnostic when it must
//! degrade.  These helpers are visual-only and never alter primitive
//! transforms or gameplay state.

use super::{FangyuanCatalogProjection, FangyuanCatalogRenderModel, FangyuanPrimitiveKind};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FangyuanSurfaceProjectionFallbackReason {
    TriplanarUsesMeshUv,
    PlanarOrTriplanarUsesPlanar,
    SphericalProjectionUsesMeshUv,
}

impl FangyuanSurfaceProjectionFallbackReason {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::TriplanarUsesMeshUv => "triplanar_uses_mesh_uv",
            Self::PlanarOrTriplanarUsesPlanar => "planar_or_triplanar_uses_planar",
            Self::SphericalProjectionUsesMeshUv => "spherical_projection_uses_mesh_uv",
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FangyuanResolvedSurfaceProjection {
    pub requested: FangyuanCatalogProjection,
    pub effective: FangyuanCatalogProjection,
    pub fallback_reason: Option<FangyuanSurfaceProjectionFallbackReason>,
}

impl FangyuanResolvedSurfaceProjection {
    pub const fn used_fallback(self) -> bool {
        self.fallback_reason.is_some()
    }
}

/// Resolve catalog projection for the stable UVs generated by this runtime.
/// Planar uses cube face UVs and sphere uses the Y-up mesh UV as a practical
/// fallback. `spherical_or_background` keeps the sphere UV and falls back to
/// mesh UV on cubes until a dedicated background projection exists.
pub const fn fangyuan_resolve_surface_projection(
    kind: FangyuanPrimitiveKind,
    requested: FangyuanCatalogProjection,
) -> FangyuanResolvedSurfaceProjection {
    match requested {
        FangyuanCatalogProjection::Planar => FangyuanResolvedSurfaceProjection {
            requested,
            effective: FangyuanCatalogProjection::Planar,
            fallback_reason: None,
        },
        FangyuanCatalogProjection::PlanarOrTriplanar => FangyuanResolvedSurfaceProjection {
            requested,
            effective: FangyuanCatalogProjection::Planar,
            fallback_reason: None,
        },
        FangyuanCatalogProjection::Triplanar => FangyuanResolvedSurfaceProjection {
            requested,
            effective: FangyuanCatalogProjection::Planar,
            fallback_reason: Some(FangyuanSurfaceProjectionFallbackReason::TriplanarUsesMeshUv),
        },
        FangyuanCatalogProjection::SphericalOrBackground => {
            let fallback_reason = if matches!(kind, FangyuanPrimitiveKind::Cube) {
                Some(FangyuanSurfaceProjectionFallbackReason::SphericalProjectionUsesMeshUv)
            } else {
                None
            };
            FangyuanResolvedSurfaceProjection {
                requested,
                effective: if fallback_reason.is_some() {
                    FangyuanCatalogProjection::Planar
                } else {
                    FangyuanCatalogProjection::SphericalOrBackground
                },
                fallback_reason,
            }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FangyuanSpecialSurfaceFallback {
    StandardOpaque,
    StandardAlphaBlend,
    UnlitDefault,
}

impl FangyuanSpecialSurfaceFallback {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::StandardOpaque => "standard_opaque",
            Self::StandardAlphaBlend => "standard_alpha_blend",
            Self::UnlitDefault => "unlit_default",
        }
    }
}

/// Return the bounded v0 fallback for catalog-known special render models.
/// Water remains a controlled opaque/alpha surface, lava keeps its emissive
/// StandardPbr policy, and sky/background uses an explicit unlit default.
pub fn fangyuan_special_surface_fallback(
    render_model: FangyuanCatalogRenderModel,
    material_family: &str,
) -> Option<FangyuanSpecialSurfaceFallback> {
    match render_model {
        FangyuanCatalogRenderModel::SpecialWater => {
            if material_family.contains("transparent") {
                Some(FangyuanSpecialSurfaceFallback::StandardAlphaBlend)
            } else {
                Some(FangyuanSpecialSurfaceFallback::StandardOpaque)
            }
        }
        FangyuanCatalogRenderModel::SpecialUnlitSky => {
            Some(FangyuanSpecialSurfaceFallback::UnlitDefault)
        }
        FangyuanCatalogRenderModel::StandardPbr
        | FangyuanCatalogRenderModel::StandardPbrOpaqueSurface
        | FangyuanCatalogRenderModel::StandardPbrEmissive => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn projection_fallbacks_keep_stable_mesh_uv_and_do_not_rotate() {
        let cube = fangyuan_resolve_surface_projection(
            FangyuanPrimitiveKind::Cube,
            FangyuanCatalogProjection::Triplanar,
        );
        assert_eq!(cube.effective, FangyuanCatalogProjection::Planar);
        assert_eq!(
            cube.fallback_reason,
            Some(FangyuanSurfaceProjectionFallbackReason::TriplanarUsesMeshUv)
        );

        let sphere = fangyuan_resolve_surface_projection(
            FangyuanPrimitiveKind::Sphere,
            FangyuanCatalogProjection::SphericalOrBackground,
        );
        assert_eq!(
            sphere.effective,
            FangyuanCatalogProjection::SphericalOrBackground
        );
        assert!(!sphere.used_fallback());
    }

    #[test]
    fn special_surface_fallbacks_are_explicit_and_bounded() {
        assert_eq!(
            fangyuan_special_surface_fallback(FangyuanCatalogRenderModel::SpecialWater, "water"),
            Some(FangyuanSpecialSurfaceFallback::StandardOpaque)
        );
        assert_eq!(
            fangyuan_special_surface_fallback(FangyuanCatalogRenderModel::SpecialUnlitSky, "sky"),
            Some(FangyuanSpecialSurfaceFallback::UnlitDefault)
        );
        assert_eq!(
            fangyuan_special_surface_fallback(
                FangyuanCatalogRenderModel::StandardPbrEmissive,
                "lava"
            ),
            None
        );
    }
}
